def scan_markdown_ghost_references(
    md_path: Path, root: Path, report: ScanReport
) -> None:
    content = read_text_safe(md_path)
    if content is None:
        return

    lines = content.splitlines()
    in_fence = False
    rel_file = rel_posix(md_path, root)

    for idx, line in enumerate(lines, start=1):
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue

        # 1a. Check Markdown links [text](target)
        for match in MD_LINK_RE.finditer(line):
            raw_target = match.group(2).strip()
            target = raw_target.split()[0] if raw_target else ""
            if not target or target.startswith(
                ("#", "http://", "https://", "mailto:", "tel:", "data:", "javascript:", "conversation://")
            ):
                continue
            if any(tok in target.lower() for tok in PLACEHOLDER_TOKENS):
                continue

            clean_target = target.split("#")[0].split("?")[0]
            if not clean_target or clean_target.startswith("file:///"):
                continue

            resolved_local = (md_path.parent / clean_target).resolve()
            resolved_root = (root / clean_target.lstrip("/")).resolve()
            if not resolved_local.exists() and not resolved_root.exists():
                report.add(
                    Finding(
                        category="ghost_reference",
                        tier="Tier 1",
                        file=rel_file,
                        line=idx,
                        end_line=idx,
                        title=f"Broken documentation link: '{clean_target}'",
                        evidence=f"Referenced link target '{clean_target}' does not exist relative to '{rel_file}' or project root.",
                        snippet=line.strip()[:120],
                    )
                )

        # 1b. Check inline code paths like `src/services/auth.py`
        for match in INLINE_CODE_RE.finditer(line):
            token = match.group(1).strip()
            if " " in token or "\t" in token or "/" not in token:
                continue
            clean_token = token.split("#")[0].split(":")[0]
            if any(tok in clean_token.lower() for tok in PLACEHOLDER_TOKENS):
                continue

            # Ignore illustrative examples in prose
            prefix_context = line[: match.start()].lower()
            if any(
                ex in prefix_context[-25:]
                for ex in ("e.g.", "for example", "such as", "如", "例如", "比如", "类似")
            ):
                continue

            ext = Path(clean_token).suffix.lower()
            starts_with_known = clean_token.startswith(PATH_PREFIXES)
            if not (starts_with_known and ext in KNOWN_PATH_EXTENSIONS):
                continue

            candidate_root = (root / clean_token.lstrip("./")).resolve()
            candidate_local = (md_path.parent / clean_token).resolve()
            if not candidate_root.exists() and not candidate_local.exists():
                report.add(
                    Finding(
                        category="ghost_reference",
                        tier="Tier 1",
                        file=rel_file,
                        line=idx,
                        end_line=idx,
                        title=f"Ghost file path in documentation: `{clean_token}`",
                        evidence=f"Inline path `{clean_token}` does not exist in workspace. High risk of misleading agent file operations.",
                        snippet=line.strip()[:120],
                    )
                )


SCRIPT_FILE_TOKEN_RE = re.compile(
    r"(?:node|ts-node|tsx|python|python3|sh|bash|zsh|deno|bun)\s+([A-Za-z0-9_./-]+\.(?:js|mjs|cjs|ts|tsx|py|sh|bash))"
)


def scan_package_json_scripts(pkg_path: Path, root: Path, report: ScanReport) -> None:
    content = read_text_safe(pkg_path)
    if not content:
        return
    try:
        data = json.loads(content)
    except json.JSONDecodeError:
        return

    scripts = data.get("scripts")
    if not isinstance(scripts, dict):
        return

    rel_file = rel_posix(pkg_path, root)
    lines = content.splitlines()

    for script_name, cmd in scripts.items():
        if not isinstance(cmd, str):
            continue
        for match in SCRIPT_FILE_TOKEN_RE.finditer(cmd):
            script_target = match.group(1)
            resolved = (pkg_path.parent / script_target).resolve()
            if not resolved.exists():
                line_no = 1
                for i, l in enumerate(lines, start=1):
                    if f'"{script_name}"' in l:
                        line_no = i
                        break
                report.add(
                    Finding(
                        category="ghost_reference",
                        tier="Tier 2",
                        file=rel_file,
                        line=line_no,
                        end_line=line_no,
                        title=f"Dead script target in package.json: '{script_name}' -> '{script_target}'",
                        evidence=f"npm script '{script_name}' invokes '{script_target}', which does not exist on disk.",
                        snippet=f'"{script_name}": "{cmd}"',
                    )
                )


ENV_KEY_RE = re.compile(r"^\s*(?:export\s+)?([A-Z][A-Z0-9_]{2,})\s*=")


def scan_shadow_env_vars(
    env_files: List[Path], all_files: List[Path], root: Path, report: ScanReport
) -> None:
    if not env_files:
        return

    non_env_corpus: List[str] = []
    for f in all_files:
        if f.name.startswith(".env"):
            continue
        if f.suffix.lower() in KNOWN_PATH_EXTENSIONS or f.name in {"Dockerfile", "Makefile", "docker-compose.yml", "docker-compose.yaml"}:
            txt = read_text_safe(f)
            if txt:
                non_env_corpus.append(txt)

    combined_corpus = "\n".join(non_env_corpus)

    for env_path in env_files:
        content = read_text_safe(env_path)
        if not content:
            continue
        rel_file = rel_posix(env_path, root)
        for idx, line in enumerate(content.splitlines(), start=1):
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            m = ENV_KEY_RE.match(stripped)
            if not m:
                continue
            env_key = m.group(1)
            if env_key in {"PATH", "HOME", "USER", "PORT", "NODE_ENV", "ENV", "DEBUG", "TZ", "LANG", "PWD", "CI"}:
                continue
            if not re.search(rf"\b{re.escape(env_key)}\b", combined_corpus):
                report.add(
                    Finding(
                        category="shadow_env_var",
                        tier="Tier 2",
                        file=rel_file,
                        line=idx,
                        end_line=idx,
                        title=f"Unreferenced environment variable `{env_key}` in {env_path.name}",
                        evidence=f"`{env_key}` is defined in {rel_file} but has 0 occurrences across all code and configuration files.",
                        snippet=stripped[:100],
                    )
                )


