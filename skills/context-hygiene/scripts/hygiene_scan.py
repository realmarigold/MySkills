def run_hygiene_scan(target_dir: Path) -> ScanReport:
    root = target_dir.resolve()
    report = ScanReport(root_path=root.as_posix())

    all_files = collect_project_files(root)
    report.files_scanned = len(all_files)

    md_files: List[Path] = []
    code_files: List[Path] = []
    env_files: List[Path] = []
    pkg_json_files: List[Path] = []

    for f in all_files:
        ext = f.suffix.lower()
        if ext in DOC_EXTENSIONS or f.name in {".cursorrules"}:
            md_files.append(f)
        if ext in CODE_EXTENSIONS:
            code_files.append(f)
        if f.name in {".env.example", ".env.sample", ".env.template"}:
            env_files.append(f)
        if f.name == "package.json":
            pkg_json_files.append(f)

    for md in md_files:
        scan_markdown_ghost_references(md, root, report)

    for pkg in pkg_json_files:
        scan_package_json_scripts(pkg, root, report)

    scan_shadow_env_vars(env_files, all_files, root, report)

    for cf in code_files:
        scan_comments_in_code_file(cf, root, report)
        if cf.suffix.lower() == ".py":
            scan_python_ast(cf, root, report)
        elif cf.suffix.lower() in {".ts", ".tsx", ".js", ".jsx", ".go", ".rs", ".java", ".c", ".cpp", ".cs"}:
            scan_cfamily_dead_branches(cf, root, report)

    scan_orphan_file_candidates(code_files, all_files, root, report)

    report.findings.sort(key=lambda x: (x.tier, x.category, x.file, x.line))
    return report


def format_text_report(report: ScanReport, max_items: int = 200) -> str:
    out: List[str] = []
    out.append("=" * 76)
    out.append("CONTEXT HYGIENE & ANTI-HALLUCINATION SCAN REPORT")
    out.append("=" * 76)
    out.append(f"Target Root   : {report.root_path}")
    out.append(f"Files Scanned : {report.files_scanned}")
    out.append(f"Total Findings: {len(report.findings)}")
    out.append("-" * 76)

    if not report.findings:
        out.append("No Automated Context Hygiene issues detected.")
        out.append("Proceed to Phase 2 manual semantic audit (Comment-Code Drift & Dual-Track check).")
        return "\n".join(out)

    by_tier: Dict[str, List[Finding]] = {"Tier 1": [], "Tier 2": []}
    for f in report.findings:
        by_tier.setdefault(f.tier, []).append(f)

    for tier_label, desc in [
        ("Tier 1", "SAFE / DETERMINISTIC CLEANUP (Commented Code, Unreachable, Ghost Links, Local Dead Private)"),
        ("Tier 2", "STRUCTURAL / REQUIRES CONFIRMATION (Orphan/Test-Only Modules, Hollow Params, Fossilized Flags, Shadow Env)"),
    ]:
        items = by_tier.get(tier_label, [])
        out.append(f"\n[{tier_label}] {desc} — {len(items)} item(s)")
        out.append("-" * 76)
        if not items:
            out.append("  (None)")
            continue
        for idx, item in enumerate(items[:max_items], start=1):
            loc = f"{item.file}:L{item.line}" if item.line == item.end_line else f"{item.file}:L{item.line}-L{item.end_line}"
            out.append(f"  {idx}. [{item.category}] {loc}")
            out.append(f"     Title   : {item.title}")
            out.append(f"     Evidence: {item.evidence}")
            if item.snippet:
                out.append(f"     Snippet : {item.snippet}")
        if len(items) > max_items:
            out.append(f"  ({len(items) - max_items} more {tier_label} items omitted)")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Scan a codebase for AI Agent hallucination triggers (dead code, ghost docs, commented-out code, hollow params)."
    )
    parser.add_argument(
        "path",
        nargs="?",
        default=".",
        help="Path to the target project directory (default: current directory).",
    )
    parser.add_argument(
        "--format",
        choices=["text", "json"],
        default="text",
        help="Output format: 'text' (human/agent readable) or 'json'.",
    )
    parser.add_argument(
        "--max-items",
        type=int,
        default=200,
        help="Maximum findings to display per tier in text mode.",
    )
    args = parser.parse_args()

    target = Path(args.path)
    if not target.exists():
        print(f"Error: target path '{target}' does not exist.", file=sys.stderr)
        return 1

    report = run_hygiene_scan(target)
    if args.format == "json":
        print(json.dumps(asdict(report), indent=2, ensure_ascii=False))
    else:
        print(format_text_report(report, max_items=args.max_items))
    return 0


if __name__ == "__main__":
    sys.exit(main())
