@dataclass
class Finding:
    category: str
    tier: str  # "Tier 1" or "Tier 2"
    file: str
    line: int
    end_line: int
    title: str
    evidence: str
    snippet: str = ""


@dataclass
class ScanReport:
    root_path: str
    files_scanned: int = 0
    findings: List[Finding] = field(default_factory=list)

    def add(self, finding: Finding) -> None:
        self.findings.append(finding)


def load_gitignore_patterns(root: Path) -> List[str]:
    gitignore = root / ".gitignore"
    if not gitignore.is_file():
        return []
    patterns: List[str] = []
    try:
        for raw_line in gitignore.read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw_line.strip()
            if not line or line.startswith("#") or line.startswith("!"):
                continue
            patterns.append(line.strip("/"))
    except OSError:
        pass
    return patterns


def is_ignored_path(path: Path, root: Path, gitignore_patterns: List[str]) -> bool:
    if any(path.name.endswith(sfx) for sfx in GENERATED_FILENAME_SUFFIXES):
        return True
    try:
        rel = path.relative_to(root)
        rel_parts = rel.parts
        rel_posix_str = rel.as_posix()
    except ValueError:
        rel_parts = path.parts
        rel_posix_str = path.as_posix()

    for part in rel_parts:
        if part in IGNORED_DIRS:
            return True
        if part.startswith(".") and part not in ALLOWED_DOT_DIRS and part not in ALLOWED_DOT_FILES:
            return True
        if part.endswith(".egg-info"):
            return True

    for pat in gitignore_patterns:
        if fnmatch.fnmatch(path.name, pat) or fnmatch.fnmatch(rel_posix_str, pat):
            return True
        for part in rel_parts:
            if fnmatch.fnmatch(part, pat):
                return True
    return False


def collect_project_files(root: Path) -> List[Path]:
    gitignore_patterns = load_gitignore_patterns(root)
    files: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        current_dir = Path(dirpath)
        dirnames[:] = [
            d
            for d in dirnames
            if d not in IGNORED_DIRS
            and not d.endswith(".egg-info")
            and not (d.startswith(".") and d not in ALLOWED_DOT_DIRS)
            and not any(fnmatch.fnmatch(d, pat) for pat in gitignore_patterns)
        ]
        for fname in filenames:
            fpath = current_dir / fname
            if not is_ignored_path(fpath, root, gitignore_patterns):
                files.append(fpath)
    return sorted(files)


def read_text_safe(path: Path) -> Optional[str]:
    try:
        if path.stat().st_size > 2 * 1024 * 1024:
            return None
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def is_generated_content(content: str) -> bool:
    head = "\n".join(content.splitlines()[:10])
    return bool(GENERATED_HEADER_RE.search(head))


def rel_posix(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def is_test_file_path(rel_path: str) -> bool:
    p = Path(rel_path)
    parts = {part.lower() for part in p.parts}
    stem = p.stem.lower()
    if parts & {"test", "tests", "__tests__", "spec", "specs", "fixtures", "e2e"}:
        return True
    if (
        stem.startswith("test_")
        or stem.endswith(("_test", ".test", ".spec"))
        or stem == "conftest"
    ):
        return True
    return False


