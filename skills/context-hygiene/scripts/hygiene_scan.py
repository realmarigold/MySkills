CODE_LINE_PATTERNS = [
    re.compile(r"^\s*(?:def|class|function|func|fn|pub\s+fn|async\s+def|async\s+function)\s+[A-Za-z_]\w*\s*[\(\{:]"),
    re.compile(r"^\s*(?:import\s+[A-Za-z0-9_.,\s*{}]+|from\s+[A-Za-z0-9_.]+\s+import\s+|#include\s+[<\"])"),
    re.compile(r"^\s*(?:const|let|var|val|mut)\s+[A-Za-z_]\w*\s*(?::\s*[^=]+)?="),
    re.compile(r"^\s*(?:if|elif|else\s+if|for|while|switch|catch)\s*[\(\s].*[\):\{]\s*$"),
    re.compile(r"^\s*(?:return|raise|throw|yield|break|continue)\b[^.;]*[;:]?\s*$"),
    re.compile(r"^\s*[A-Za-z_][\w\.\[\]]*\s*(?:\+|-|\*|/)?=\s*[^=]"),
    re.compile(r"^\s*[A-Za-z_][\w\.]*\([^)]*\)\s*;?\s*$"),
    re.compile(r"^\s*[\}\]);,]+\s*$"),
]

PROSE_IGNORE_PATTERNS = [
    re.compile(r"^\s*(?:http://|https://|ftp://)"),
    re.compile(r"^\s*(?:Copyright|Licensed|SPDX-License-Identifier|Permission is hereby granted|All rights reserved)", re.IGNORECASE),
    re.compile(r"^\s*(?:eslint-|prettier-|tslint:|@ts-|type:\s*ignore|noqa|pragma:|nolint|fmt:|noinspection|#\[allow)"),
    re.compile(r"^\s*(?:@[a-zA-Z]+|\*\s+@[a-zA-Z]+|:param\b|:return\b|:raises\b|Args:|Returns:|Raises:|Example:|Examples:|Note:|Warning:)"),
    re.compile(r"^\s*[-=*#_]{3,}\s*$"),
]

# Match explicit debt markers or tombstone comments without false-positiving on prose 'legacy'
_DEBT_TAG_WORDS = "|".join(["TO" + "DO", "FIX" + "ME", "HA" + "CK", "XX" + "X"])
EXPLICIT_DEBT_TAG_RE = re.compile(rf"\b({_DEBT_TAG_WORDS})\b\s*[:(\-\[]?", re.IGNORECASE)
DEPRECATED_TAG_RE = re.compile(r"(?:@deprecated\b|\b(?:DEPRECATED|OBSOLETE)\s*[:\-])", re.IGNORECASE)
TOMBSTONE_RE = re.compile(
    r"(?:旧逻辑|已废弃|暂时注释|临时兼容|待删除|removed\s+old|deleted\s+legacy|commented\s+out\s+for\s+now|no\s+longer\s+used)",
    re.IGNORECASE,
)
PAST_DATE_OR_VER_RE = re.compile(r"\b(201[5-9]|202[0-5]|v0\.\d+|v1\.0)\b", re.IGNORECASE)

C_BLOCK_COMMENT_RE = re.compile(r"/\*([^*][\s\S]*?)\*/")


def is_code_like_comment_line(text: str) -> bool:
    stripped = text.strip()
    if not stripped or len(stripped) < 3:
        return False
    for pat in PROSE_IGNORE_PATTERNS:
        if pat.search(stripped):
            return False
    words = stripped.split()
    if len(words) >= 6 and stripped.endswith(".") and not stripped.endswith(");"):
        return False
    for pat in CODE_LINE_PATTERNS:
        if pat.search(stripped):
            return True
    if stripped.endswith((";", "{", "}", "):", "},", "],")) and not stripped.startswith(("-", "*", "#")):
        return True
    return False


def evaluate_comment_block_for_code(
    block_lines: List[Tuple[int, str]], rel_file: str, report: ScanReport
) -> None:
    if len(block_lines) < 2:
        return
    code_hits = sum(1 for _, txt in block_lines if is_code_like_comment_line(txt))
    structural_hits = sum(
        1
        for _, txt in block_lines
        if txt.strip().endswith((";", "{", "}"))
        or re.match(
            r"^\s*(?:def |class |function |const |let |var |import |from |return |if |for |while )",
            txt.strip(),
        )
    )
    if (
        (code_hits >= 2 and code_hits / len(block_lines) >= 0.5)
        or (len(block_lines) >= 4 and code_hits >= 3)
        or (len(block_lines) == 2 and structural_hits == 2)
    ):
        start_ln = block_lines[0][0]
        end_ln = block_lines[-1][0]
        preview = " | ".join(txt.strip() for _, txt in block_lines[:3] if txt.strip())
        report.add(
            Finding(
                category="commented_out_code",
                tier="Tier 1",
                file=rel_file,
                line=start_ln,
                end_line=end_ln,
                title=f"Commented-out code block ({len(block_lines)} lines)",
                evidence=f"Contiguous comment block (L{start_ln}-L{end_ln}) matches executable code syntax ({code_hits}/{len(block_lines)} lines).",
                snippet=preview[:140],
            )
        )


def scan_comments_in_code_file(
    file_path: Path, root: Path, report: ScanReport
) -> None:
    content = read_text_safe(file_path)
    if not content or is_generated_content(content):
        return

    ext = file_path.suffix.lower()
    rel_file = rel_posix(file_path, root)
    lines = content.splitlines()

    if ext in {".py", ".rb", ".sh", ".bash", ".yaml", ".yml", ".toml"}:
        prefix_re = re.compile(r"^\s*#(.*)$")
        supports_c_block = False
    else:
        prefix_re = re.compile(r"^\s*//(.*)$")
        supports_c_block = True

    block_lines: List[Tuple[int, str]] = []

    for idx, line in enumerate(lines, start=1):
        m = prefix_re.match(line)
        if m:
            comment_body = m.group(1)
            tomb_match = TOMBSTONE_RE.search(comment_body)
            debt_match = EXPLICIT_DEBT_TAG_RE.search(comment_body)
            dep_match = DEPRECATED_TAG_RE.search(comment_body)
            has_old_anchor = bool(PAST_DATE_OR_VER_RE.search(comment_body))

            if tomb_match:
                report.add(
                    Finding(
                        category="stale_marker",
                        tier="Tier 1",
                        file=rel_file,
                        line=idx,
                        end_line=idx,
                        title=f"Tombstone comment marker ({tomb_match.group(0)})",
                        evidence="Tombstone comment describing removed/disabled code pollutes context; history belongs in Git.",
                        snippet=line.strip()[:120],
                    )
                )
            elif dep_match or (debt_match and has_old_anchor):
                tag_str = (dep_match or debt_match).group(0).strip()  # type: ignore[union-attr]
                report.add(
                    Finding(
                        category="stale_marker",
                        tier="Tier 2",
                        file=rel_file,
                        line=idx,
                        end_line=idx,
                        title=f"Stale deprecation/debt marker ({tag_str})",
                        evidence="Expired debt or deprecation marker can mislead agents about current module status.",
                        snippet=line.strip()[:120],
                    )
                )
            block_lines.append((idx, comment_body))
        else:
            evaluate_comment_block_for_code(block_lines, rel_file, report)
            block_lines.clear()
    evaluate_comment_block_for_code(block_lines, rel_file, report)
    block_lines.clear()

    # Also check C-style /* ... */ block comments (excluding /** JSDoc)
    if supports_c_block:
        for match in C_BLOCK_COMMENT_RE.finditer(content):
            body = match.group(1)
            start_line = content.count("\n", 0, match.start()) + 1
            raw_sublines = body.splitlines()
            cleaned_sublines: List[Tuple[int, str]] = []
            for offset, sub in enumerate(raw_sublines):
                cleaned = re.sub(r"^\s*\*\s?", "", sub).strip()
                if cleaned:
                    cleaned_sublines.append((start_line + offset, cleaned))
            evaluate_comment_block_for_code(cleaned_sublines, rel_file, report)


