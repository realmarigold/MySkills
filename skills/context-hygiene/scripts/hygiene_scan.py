def _get_decorator_names(node: ast.AST) -> Set[str]:
    names: Set[str] = set()
    for dec in getattr(node, "decorator_list", []):
        if isinstance(dec, ast.Name):
            names.add(dec.id.lower())
        elif isinstance(dec, ast.Attribute):
            names.add(dec.attr.lower())
        elif isinstance(dec, ast.Call):
            func = dec.func
            if isinstance(func, ast.Name):
                names.add(func.id.lower())
            elif isinstance(func, ast.Attribute):
                names.add(func.attr.lower())
    return names


def _is_stub_body(body: List[ast.stmt]) -> bool:
    meaningful: List[ast.stmt] = []
    for idx, stmt in enumerate(body):
        if (
            idx == 0
            and isinstance(stmt, ast.Expr)
            and isinstance(stmt.value, ast.Constant)
            and isinstance(stmt.value.value, str)
        ):
            continue
        meaningful.append(stmt)
    if not meaningful:
        return True
    if len(meaningful) == 1:
        only = meaningful[0]
        if isinstance(only, ast.Pass):
            return True
        if isinstance(only, ast.Expr) and isinstance(only.value, ast.Constant) and only.value.value is Ellipsis:
            return True
        if isinstance(only, ast.Raise):
            return True
        if isinstance(only, ast.Return) and (
            only.value is None
            or (isinstance(only.value, ast.Constant) and only.value.value is None)
        ):
            return True
    return False


def _check_stmt_list_unreachable_and_string_blocks(
    stmts: List[ast.stmt],
    rel_file: str,
    lines: List[str],
    report: ScanReport,
    is_docstring_container: bool = False,
) -> None:
    for idx, stmt in enumerate(stmts):
        # Detect non-docstring standalone multiline strings used to comment out code
        if (
            isinstance(stmt, ast.Expr)
            and isinstance(stmt.value, ast.Constant)
            and isinstance(stmt.value.value, str)
            and not (is_docstring_container and idx == 0)
        ):
            str_val = stmt.value.value
            str_lines = [l for l in str_val.splitlines() if l.strip()]
            if len(str_lines) >= 2:
                start_ln = getattr(stmt, "lineno", 1)
                numbered = [(start_ln + i, l) for i, l in enumerate(str_lines)]
                evaluate_comment_block_for_code(numbered, rel_file, report)

        if isinstance(stmt, TERMINATOR_NODES) and idx + 1 < len(stmts):
            next_stmt = stmts[idx + 1]
            last_stmt = stmts[-1]
            start_ln = getattr(next_stmt, "lineno", 1)
            end_ln = getattr(last_stmt, "end_lineno", start_ln) or start_ln
            snip = lines[start_ln - 1].strip() if 0 < start_ln <= len(lines) else ""
            report.add(
                Finding(
                    category="unreachable_code",
                    tier="Tier 1",
                    file=rel_file,
                    line=start_ln,
                    end_line=end_ln,
                    title="Unreachable statements after return/raise/break/continue",
                    evidence=f"Lines {start_ln}-{end_ln} appear after a terminating `{type(stmt).__name__.lower()}` statement in the same block.",
                    snippet=snip[:120],
                )
            )
            break

        is_sub_container = isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        for attr in ("body", "orelse", "finalbody"):
            sub = getattr(stmt, attr, None)
            if isinstance(sub, list):
                _check_stmt_list_unreachable_and_string_blocks(
                    sub,
                    rel_file,
                    lines,
                    report,
                    is_docstring_container=(is_sub_container and attr == "body"),
                )
        if isinstance(stmt, ast.Try):
            for handler in stmt.handlers:
                _check_stmt_list_unreachable_and_string_blocks(handler.body, rel_file, lines, report)
        elif hasattr(ast, "Match") and isinstance(stmt, getattr(ast, "Match")):
            for case in getattr(stmt, "cases", []):
                _check_stmt_list_unreachable_and_string_blocks(case.body, rel_file, lines, report)


def scan_python_ast(file_path: Path, root: Path, report: ScanReport) -> None:
    content = read_text_safe(file_path)
    if not content or is_generated_content(content):
        return
    try:
        tree = ast.parse(content, filename=str(file_path))
    except SyntaxError:
        return

    rel_file = rel_posix(file_path, root)
    lines = content.splitlines()
    in_test_file = is_test_file_path(rel_file)

    # 1. Unreachable code & non-docstring multiline string code graveyards
    _check_stmt_list_unreachable_and_string_blocks(
        tree.body, rel_file, lines, report, is_docstring_container=True
    )

    # 2. Collect top-level constant boolean/int flags assigned exactly once
    top_assign_counts: Dict[str, int] = {}
    top_bool_consts: Dict[str, Tuple[bool, int]] = {}
    mutated_globals: Set[str] = set()

    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
            name = stmt.targets[0].id
            top_assign_counts[name] = top_assign_counts.get(name, 0) + 1
            if isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, bool):
                top_bool_consts[name] = (stmt.value.value, stmt.lineno)
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value is not None:
            name = stmt.target.id
            top_assign_counts[name] = top_assign_counts.get(name, 0) + 1
            if isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, bool):
                top_bool_consts[name] = (stmt.value.value, stmt.lineno)

    for node in ast.walk(tree):
        if isinstance(node, ast.Global):
            mutated_globals.update(node.names)
        elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name):
            mutated_globals.add(node.target.id)
        elif isinstance(node, ast.Assign) and node not in tree.body:
            for tgt in node.targets:
                if isinstance(tgt, ast.Name):
                    mutated_globals.add(tgt.id)

    immutable_flags: Dict[str, Tuple[bool, int]] = {
        k: v
        for k, v in top_bool_consts.items()
        if top_assign_counts.get(k, 0) == 1 and k not in mutated_globals
    }

    # 3. Check `If` nodes for constant conditions or fossilized flags
    for node in ast.walk(tree):
        if isinstance(node, ast.If):
            test = node.test
            if isinstance(test, ast.Constant) and isinstance(test.value, (bool, int)):
                ln = node.lineno
                end_ln = getattr(node, "end_lineno", ln) or ln
                report.add(
                    Finding(
                        category="dead_branch",
                        tier="Tier 1",
                        file=rel_file,
                        line=ln,
                        end_line=end_ln,
                        title=f"Constant condition branch: `if {repr(test.value)}:`",
                        evidence=f"Condition at L{ln} evaluates to constant `{repr(test.value)}`, making one branch permanently dead.",
                        snippet=lines[ln - 1].strip()[:120] if 0 < ln <= len(lines) else "",
                    )
                )
            elif isinstance(test, ast.Name) and test.id in immutable_flags:
                flag_val, def_ln = immutable_flags[test.id]
                ln = node.lineno
                end_ln = getattr(node, "end_lineno", ln) or ln
                report.add(
                    Finding(
                        category="fossilized_flag",
                        tier="Tier 2",
                        file=rel_file,
                        line=ln,
                        end_line=end_ln,
                        title=f"Fossilized feature flag `{test.id}` (hardcoded to `{flag_val}` at L{def_ln})",
                        evidence=f"`{test.id}` is hardcoded to `{flag_val}` at L{def_ln} and never mutated in {rel_file}, creating a zombie branch at L{ln}.",
                        snippet=lines[ln - 1].strip()[:120] if 0 < ln <= len(lines) else "",
                    )
                )

    # 4. Check hollow / unused function parameters (on production code, excluding overrides/callbacks)
    if not in_test_file:
        inherited_class_methods: Set[ast.AST] = set()
        nested_functions: Set[ast.AST] = set()

        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                base_names = []
                for b in node.bases:
                    if isinstance(b, ast.Name):
                        base_names.append(b.id)
                    elif isinstance(b, ast.Attribute):
                        base_names.append(b.attr)
                    else:
                        base_names.append("<expr>")
                has_non_object_base = any(bn != "object" for bn in base_names)
                if has_non_object_base:
                    for item in node.body:
                        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            inherited_class_methods.add(item)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for child in ast.walk(ast.Module(body=node.body, type_ignores=[])):
                    if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        nested_functions.add(child)

        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if node in inherited_class_methods or node in nested_functions:
                continue
            fn_name_lower = node.name.lower()
            if node.name.startswith("__") and node.name.endswith("__"):
                continue
            if fn_name_lower in CALLBACK_FUNCTION_NAMES:
                continue
            if fn_name_lower.startswith(CALLBACK_FUNCTION_PREFIXES):
                continue
            if fn_name_lower.endswith(("_side_effect", "_callback", "_handler", "_hook")):
                continue
            if _is_stub_body(node.body):
                continue

            decs = _get_decorator_names(node)
            if decs & IGNORED_DECORATOR_KEYWORDS:
                continue

            all_arg_nodes = (
                list(getattr(node.args, "posonlyargs", []))
                + list(node.args.args)
                + list(node.args.kwonlyargs)
            )
            param_names_set = {a.arg for a in all_arg_nodes}
            if any(sig_set.issubset(param_names_set) for sig_set in FRAMEWORK_SIGNATURE_SETS):
                continue

            candidate_params: List[ast.arg] = []
            for arg in all_arg_nodes:
                if arg.arg in {"self", "cls", "_"} or arg.arg.startswith("_"):
                    continue
                candidate_params.append(arg)

            if not candidate_params:
                continue

            used_names: Set[str] = set()
            uses_dynamic_scope = False
            for sub in ast.walk(ast.Module(body=node.body, type_ignores=[])):
                if isinstance(sub, ast.Name) and isinstance(sub.ctx, ast.Load):
                    used_names.add(sub.id)
                    if sub.id in {"locals", "vars", "eval", "exec"}:
                        uses_dynamic_scope = True

            if uses_dynamic_scope:
                continue

            for arg in candidate_params:
                if arg.arg not in used_names:
                    ln = getattr(arg, "lineno", node.lineno)
                    report.add(
                        Finding(
                            category="hollow_parameter",
                            tier="Tier 2",
                            file=rel_file,
                            line=ln,
                            end_line=ln,
                            title=f"Hollow/unused parameter `{arg.arg}` in `{node.name}()`",
                            evidence=f"Parameter `{arg.arg}` is declared in `{node.name}()` signature but never read in the function body. Can mislead agents into passing ineffective arguments.",
                            snippet=lines[node.lineno - 1].strip()[:120] if 0 < node.lineno <= len(lines) else "",
                        )
                    )

    # 5. Check unused module-level private functions/classes (`_name`)
    all_loaded_names: Set[str] = set()
    exported_in_dunder_all: Set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            all_loaded_names.add(node.id)
        elif isinstance(node, ast.Assign):
            for tgt in node.targets:
                if isinstance(tgt, ast.Name) and tgt.id == "__all__":
                    if isinstance(node.value, (ast.List, ast.Tuple, ast.Set)):
                        for elt in node.value.elts:
                            if isinstance(elt, ast.Constant) and isinstance(elt.value, str):
                                exported_in_dunder_all.add(elt.value)

    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if (
                stmt.name.startswith("_")
                and not stmt.name.startswith("__")
                and stmt.name not in all_loaded_names
                and stmt.name not in exported_in_dunder_all
                and not _get_decorator_names(stmt)
            ):
                ln = stmt.lineno
                end_ln = getattr(stmt, "end_lineno", ln) or ln
                report.add(
                    Finding(
                        category="dead_private_symbol",
                        tier="Tier 1",
                        file=rel_file,
                        line=ln,
                        end_line=end_ln,
                        title=f"Unused module-private symbol `{stmt.name}`",
                        evidence=f"Private definition `{stmt.name}` (L{ln}-L{end_ln}) has 0 references inside `{rel_file}`.",
                        snippet=lines[ln - 1].strip()[:120] if 0 < ln <= len(lines) else "",
                    )
                )


# ---------------------------------------------------------------------------
# 4. Constant Dead Branches in C-Family / TS / JS / Go / Rust
# ---------------------------------------------------------------------------

CFAMILY_CONST_IF_RE = re.compile(
    r"^\s*if\s*(?:\(\s*(?:false|true|0|1)\s*\)|\s+(?:false|true)\s*\{)"
)


def scan_cfamily_dead_branches(
    file_path: Path, root: Path, report: ScanReport
) -> None:
    content = read_text_safe(file_path)
    if not content or is_generated_content(content):
        return
    rel_file = rel_posix(file_path, root)
    for idx, line in enumerate(content.splitlines(), start=1):
        if CFAMILY_CONST_IF_RE.search(line):
            report.add(
                Finding(
                    category="dead_branch",
                    tier="Tier 1",
                    file=rel_file,
                    line=idx,
                    end_line=idx,
                    title="Hardcoded constant `if (true/false)` branch",
                    evidence=f"Line {idx} uses a literal boolean/integer constant in an `if` condition.",
                    snippet=line.strip()[:120],
                )
            )


# ---------------------------------------------------------------------------
# 5. Orphaned Source File Candidates & Test-Only Zombie Modules
# ---------------------------------------------------------------------------

STANDALONE_ENTRYPOINT_RE = re.compile(
    r"(?:if\s+__name__\s*==\s*['\"]__main__['\"]|func\s+main\s*\(|fn\s+main\s*\(|public\s+static\s+void\s+main\s*\()"
)


def has_standalone_entrypoint(content: str) -> bool:
    if content.startswith("#!"):
        return True
    return bool(STANDALONE_ENTRYPOINT_RE.search(content))


def scan_orphan_file_candidates(
    code_files: List[Path], all_files: List[Path], root: Path, report: ScanReport
) -> None:
    if len(code_files) <= 1:
        return

    file_contents: Dict[Path, str] = {}
    is_test_map: Dict[Path, bool] = {}

    for f in all_files:
        if f.suffix.lower() in KNOWN_PATH_EXTENSIONS or f.name in {"Dockerfile", "Makefile", "Procfile"}:
            txt = read_text_safe(f)
            if txt:
                file_contents[f] = txt
                is_test_map[f] = is_test_file_path(rel_posix(f, root))

    for candidate in code_files:
        stem = candidate.stem
        rel_path = rel_posix(candidate, root)
        rel_parts = set(Path(rel_path).parts)

        if is_test_map.get(candidate, False):
            continue
        if stem.lower() in ENTRYPOINT_PATTERNS:
            continue
        if stem.endswith((".config", ".d", ".setup", ".stories")):
            continue
        if rel_parts & FRAMEWORK_DIRS:
            continue
        if candidate.name.endswith(".d.ts"):
            continue

        txt = file_contents.get(candidate, "")
        if is_generated_content(txt) or has_standalone_entrypoint(txt):
            continue

        prod_refs = 0
        test_refs = 0
        pattern = re.compile(rf"\b{re.escape(stem)}\b")

        for other_file, other_txt in file_contents.items():
            if other_file == candidate:
                continue
            if pattern.search(other_txt):
                if is_test_map.get(other_file, False):
                    test_refs += 1
                else:
                    prod_refs += 1
                    break

        total_lines = len(txt.splitlines()) if txt else 1
        first_line = txt.splitlines()[0].strip()[:100] if txt and txt.splitlines() else ""

        if prod_refs == 0 and test_refs == 0:
            report.add(
                Finding(
                    category="orphan_file_candidate",
                    tier="Tier 2",
                    file=rel_path,
                    line=1,
                    end_line=max(1, total_lines),
                    title=f"Orphan file candidate: `{rel_path}` (0 incoming references)",
                    evidence=f"Module `{stem}` has 0 references across all production, config, doc, and test files.",
                    snippet=first_line,
                )
            )
        elif prod_refs == 0 and test_refs > 0:
            report.add(
                Finding(
                    category="test_only_module",
                    tier="Tier 2",
                    file=rel_path,
                    line=1,
                    end_line=max(1, total_lines),
                    title=f"Test-only zombie module: `{rel_path}` (0 prod refs, {test_refs} test file ref(s))",
                    evidence=f"Module `{stem}` has 0 references in production code/configs and is kept alive solely by {test_refs} test file(s).",
                    snippet=first_line,
                )
            )


